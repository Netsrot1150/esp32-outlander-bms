#pragma once
#include <stdint.h>
#include "cmu.h"
// Ramar ur en riktig CAN-dump från två Outlander-CMU:er (knoxsp/OutlanderCANManInTheMiddle,
// data/outlander_cmu_can_dump_2_modules). CMU 1 har 4 celler (skickar aldrig 0x613), CMU 0xB har 8.
struct DumpFrame { uint16_t id; uint8_t d[8]; };
static const DumpFrame DUMP[] = {
  {0x6B1, {0x00, 0x30, 0x3C, 0x3C, 0x3B, 0x3B, 0x3B, 0xFF}},
  {0x6B2, {0x0F, 0x75, 0x0F, 0x78, 0x0F, 0x78, 0x0F, 0x78}},
  {0x6B3, {0x0F, 0x78, 0x0F, 0x76, 0x0F, 0x76, 0x0F, 0x79}},
  {0x6B4, {0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF}},
  {0x611, {0x00, 0x30, 0x3B, 0x3B, 0x3B, 0x3B, 0x3B, 0xFF}},
  {0x612, {0x0F, 0x7F, 0x0F, 0x7B, 0x0F, 0x7C, 0x0F, 0x7C}},
  {0x614, {0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF}},
};
static const int DUMP_N = sizeof(DUMP) / sizeof(DUMP[0]);

inline void feedDump(PackState& ps, uint32_t nowMs) {
  for (int i = 0; i < DUMP_N; i++) decodeFrame(ps, DUMP[i].id, DUMP[i].d, 8, nowMs);
}
